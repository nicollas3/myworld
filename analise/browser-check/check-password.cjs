const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');
const base = process.env.NEUROCARE_WEB_PATH || path.resolve(__dirname, '../../src/NeuroCare.Web');
const script = fs.readFileSync(path.join(base, 'wwwroot/js/password-toggle.js'), 'utf8');
const login = fs.readFileSync(path.join(base, 'Views/Account/Login.cshtml'), 'utf8');
const buttonMarkup = login.match(/<button type="button"\s+class="neurocare-password-button"[\s\S]*?<\/button>/)[0];
const loginDom = new JSDOM(`<input id="Password" type="password">${buttonMarkup}`, { runScripts: 'outside-only' });
loginDom.window.eval(script);
const loginButton = loginDom.window.document.querySelector('button');
const icons = loginButton.querySelectorAll('svg').length;
assert.ok(icons > 0);
loginButton.click();
assert.equal(loginDom.window.document.querySelector('input').type, 'text');
assert.equal(loginButton.getAttribute('aria-pressed'), 'true');
assert.equal(loginButton.classList.contains('is-visible'), true);
assert.equal(loginButton.querySelectorAll('svg').length, icons);
loginButton.click();
assert.equal(loginDom.window.document.querySelector('input').type, 'password');
assert.equal(loginButton.getAttribute('aria-pressed'), 'false');
assert.equal(loginButton.classList.contains('is-visible'), false);
assert.equal(loginButton.querySelectorAll('svg').length, icons);
loginDom.window.close();
console.log('Login: alternância e preservação dos ícones verificadas.');

const reset = fs.readFileSync(path.join(base, 'Views/Account/ResetPassword.cshtml'), 'utf8');
const resetButton = reset.match(/<button[^>]+data-toggle-password="#NewPassword"[^>]*>[\s\S]*?<\/button>/)[0];
const resetDom = new JSDOM(`<input id="NewPassword" type="password">${resetButton}`, { runScripts: 'outside-only' });
resetDom.window.eval(script);
const button = resetDom.window.document.querySelector('button');
button.click();
assert.equal(resetDom.window.document.querySelector('input').type, 'text');
assert.equal(button.getAttribute('aria-pressed'), 'true');
button.click();
assert.equal(resetDom.window.document.querySelector('input').type, 'password');
assert.equal(button.getAttribute('aria-pressed'), 'false');
resetDom.window.close();
console.log('Redefinição de senha: alternância verificada.');

const absentDom = new JSDOM('<button data-toggle-password=""></button><button data-toggle-password="#Missing"></button>', { runScripts: 'outside-only' });
assert.doesNotThrow(() => absentDom.window.eval(script));
absentDom.window.document.querySelectorAll('button').forEach(b => b.click());
absentDom.window.close();
console.log('Alvos vazios/ausentes: inicialização sem erro. 3 verificações DOM concluídas.');
